"""Phase 3 downstream: accuracy of the six stat families with the frozen stat ladders fed (a) the frozen minutes, (b) JRM minutes.
Conditional frame (players who played), common yardstick for CRPS = negative-binomial with development-fitted dispersion bins per variant,
game-clustered paired bootstrap CIs.   python evaluate_downstream.py OUT.md
"""
import sys
sys.path.insert(0, ".."); sys.path.insert(0, ".")
import numpy as np, pandas as pd
from pf_core import models
from nba.common import FAMILIES, SUPPORT_K, VAL, HOLDOUT, DEV
from nba.evaluate import diff_ci
from nba import minutes_jrm as jrm

out_path = sys.argv[1]
SUF = sys.argv[2] if len(sys.argv) > 2 else ""
f = pd.read_parquet("../.cache/features.parquet", columns=["game_id", "team", "season", "pid", "played", "minutes", "in_box", "dnp", "dnp_reason", "pts", "reb", "ast", "fg3m",
                    "fga", "pra", "start_p_ewm8", "games_in_season", "team_changed", "games_with_team", "minutes_p_n", "missed_streak", "minutes_p_ewm8"])
mp = pd.read_parquet("../.cache/minutes_preds.parquet")
f = f.join(mp[["E", "p_play"]])
f["elig"] = jrm.eligible_flag(f)
g = f.groupby(["game_id", "team"])
f["n_elig"] = g.elig.transform("sum")
f["lvl"] = f.minutes_p_ewm8.fillna(0)
f["rank"] = f.groupby(["game_id", "team"])["lvl"].rank(ascending=False, method="first")
t9 = f[f["rank"] <= 9].groupby(["game_id", "team"])["played"].mean().rename("top9")
f = f.join(t9, on=["game_id", "team"])
Ms = (f.p_play * f.E).groupby([f.game_id, f.team]).transform("sum")
f["recon_scale"] = np.where((Ms / 241.5 - 1).abs() > 0.12, (241.5 / Ms).clip(0.55, 1.45), 1.0)
f["bigM"] = (Ms / 241.5 - 1).abs() > 0.12
f["split"] = np.where(f.season.isin(DEV), "dev", np.where(f.season.isin(VAL), "val", np.where(f.season.isin(HOLDOUT), "holdout", "burn")))
f = f[f.season >= 2018]
inc = pd.concat([pd.read_parquet(f"../.cache/incumbent_{s}.parquet") for s in (2023, 2024, 2025, 2026)]).set_index(["game_id", "pid"])

lines = []
def out(s=""):
    print(s); lines.append(s)
def fmt(r):
    return "—" if r is None else f"{r['mean_diff']:+.4f} [{r['ci95'][0]:+.4f}, {r['ci95'][1]:+.4f}]"

SUB = [("all players", lambda P: P.played),
       ("established starters", lambda P: P.start_p_ewm8.fillna(0) >= .5),
       ("bench-role", lambda P: P.start_p_ewm8.fillna(0) < .5),
       ("new-to-team", lambda P: (P.team_changed == 1) | (P.games_with_team < 5)),
       ("< 3 career games", lambda P: P.minutes_p_n.fillna(0) < 3),
       ("first five games of season", lambda P: P.games_in_season <= 4),
       ("deep rotation (15+ eligible)", lambda P: P.n_elig >= 15),
       ("full health (top-9 present)", lambda P: P.top9 >= .999),
       ("frozen gate needs LARGE normalisation", lambda P: P.bigM)]

out("# Downstream: six stat families with frozen vs JRM minutes (generated by evaluate_downstream.py)\n")
out("Variants: **frozen** = cached frozen stat ladder `E` (frozen minutes E); **frozen+gate** = frozen scaled by the live reconciliation gate; **JRM** = same ladder, "
    "same frozen hyper-parameters, minutes replaced by the JRM forecast; **frozen E_inj** = ladder with E_inj minutes + absence features; **JRM|set** = ladder with JRM-given-eligible-set minutes.\n")
summary = []
for fam, (col, gkey, rungs) in FAMILIES.items():
    K = SUPPORT_K[col]
    fr = pd.read_parquet(f"../.cache/stats_{col}.parquet")
    V = {"frozen": fr["E"], "frozen_inj": pd.read_parquet(f"../.cache/ds_frozen_inj_{col}{SUF}.parquet")["E_inj"],
         "jrm": pd.read_parquet(f"../.cache/ds_jrm_{col}{SUF}.parquet")["E"], "jrm_set": pd.read_parquet(f"../.cache/ds_jrm_set_{col}{SUF}.parquet")["E"]}
    P = f.join(pd.DataFrame(V), how="inner")
    P = P[P.played & P[col].notna()].copy()
    P["frozen_gate"] = P["frozen"] * P["recon_scale"]
    P = P.join(inc[[f"{col}_mean", f"{col}_crps"]].rename(columns={f"{col}_mean": "inc", f"{col}_crps": "inc_crps"}), on=["game_id", "pid"])
    y = P[col].to_numpy(float)
    dev = (P.split == "dev").to_numpy()
    names = {"frozen": "Frozen (minutes E)", "frozen_gate": "Frozen + live gate scale", "jrm": "JRM minutes", "frozen_inj": "Frozen E_inj", "jrm_set": "JRM | eligible set"}
    crps = {}
    for k in names:
        mu = np.maximum(P[k].to_numpy(float), 0.05)
        prm = models.fit_dist_params("nb_binned", y[dev], mu[dev], K=K, n_bins=6)
        crps[k] = models.make_dist(prm, mu).crps(y)
    out(f"\n## {fam}  (conditional on playing; NB yardstick)\n")
    for sp in ("val", "holdout"):
        out(f"\n### {sp}\n")
        out("| subgroup | n | model | MAE | bias | CRPS | ΔCRPS vs frozen [95% CI] | ΔMAE vs frozen [95% CI] |\n|---|---:|---|---:|---:|---:|---|---|")
        for sname, fn in SUB:
            m = (fn(P) & (P.split == sp)).to_numpy()
            if m.sum() < 300:
                out(f"| {sname} | {int(m.sum())} | (< 300, not reported) | | | | | |")
                continue
            for k, ref in (("frozen", None), ("frozen_gate", "frozen"), ("jrm", "frozen"), ("frozen_inj", "frozen"), ("jrm_set", "frozen_inj")):
                if sname != "all players" and k in ("frozen_gate", "frozen_inj"):
                    continue
                mu = P[k].to_numpy(float)[m]
                ae = np.abs(mu - y[m])
                dc = diff_ci(crps[k][m], crps[ref][m], P.game_id.to_numpy()[m]) if ref else None
                da = diff_ci(ae, np.abs(P[ref].to_numpy(float)[m] - y[m]), P.game_id.to_numpy()[m]) if ref else None
                tag = names[k] + (" (Δ vs frozen E_inj)" if k == "jrm_set" else "")
                out(f"| {sname} | {int(m.sum()):,} | {tag} | {ae.mean():.3f} | {np.mean(mu - y[m]):+.3f} | {crps[k][m].mean():.4f} | {fmt(dc)} | {fmt(da)} |")
            if sname == "all players":
                mi = m & P.inc.notna().to_numpy()
                if mi.sum() > 500:
                    out(f"| all players, common rows with the incumbent | {int(mi.sum()):,} | Incumbent simulator | {np.abs(P.inc.to_numpy()[mi]-y[mi]).mean():.3f} | {np.mean(P.inc.to_numpy()[mi]-y[mi]):+.3f} | {np.nanmean(P.inc_crps.to_numpy()[mi]):.4f} | | |")
                    for k in ("frozen", "jrm"):
                        dc = diff_ci(crps[k][mi], P.inc_crps.to_numpy()[mi], P.game_id.to_numpy()[mi])
                        out(f"| all players, common rows | {int(mi.sum()):,} | {names[k]} vs incumbent | {np.abs(P[k].to_numpy(float)[mi]-y[mi]).mean():.3f} | | {crps[k][mi].mean():.4f} | {fmt(dc)} | |")
        # one-line summary for the roll-up
    for sp in ("val", "holdout"):
        m = (P.split == sp).to_numpy()
        for k, ref in (("jrm", "frozen"), ("jrm_set", "frozen_inj")):
            summary.append((fam, sp, k, ref, diff_ci(crps[k][m], crps[ref][m], P.game_id.to_numpy()[m]), diff_ci(np.abs(P[k].to_numpy(float)[m] - y[m]), np.abs(P[ref].to_numpy(float)[m] - y[m]), P.game_id.to_numpy()[m]), int(m.sum())))
out("\n## Roll-up: ΔCRPS and ΔMAE of the JRM variants against their frozen counterparts (negative = JRM better)\n")
out("| family | split | n | JRM vs frozen: ΔCRPS [95% CI] | ΔMAE [95% CI] | JRM|set vs frozen E_inj: ΔCRPS [95% CI] | ΔMAE [95% CI] |\n|---|---|---:|---|---|---|---|")
for fam in FAMILIES:
    for sp in ("val", "holdout"):
        a = [s for s in summary if s[0] == fam and s[1] == sp and s[2] == "jrm"][0]
        b = [s for s in summary if s[0] == fam and s[1] == sp and s[2] == "jrm_set"][0]
        out(f"| {fam} | {sp} | {a[6]:,} | {fmt(a[4])} | {fmt(a[5])} | {fmt(b[4])} | {fmt(b[5])} |")
open(out_path, "w").write("\n".join(lines))
