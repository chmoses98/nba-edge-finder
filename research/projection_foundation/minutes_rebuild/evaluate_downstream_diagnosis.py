"""Downstream diagnosis, historical walk-forward (strictly earlier seasons train, no test-season information): which stat-model recipe does the minutes engine need?

Configurations (all six stat families, conditional on playing, validation 2022-23/2023-24 and holdout 2024-25/2025-26):
  P0  production frozen      live recipe (minutes input finite only in the test season), frozen minutes E, THEN the live reconciliation gate (minutes scale)   <- control
  P1  JRM + existing models  live recipe, JRM minutes, no gate needed (budget conserved)                                                                     <- current candidate
  P2  JRM + refitted models  history-consistent recipe: the stat ladder trained with JRM walk-forward minutes on every history row, served with JRM minutes  <- challenger
  P3  frozen + refitted      same history-consistent recipe with the frozen minutes (attribution: what the recipe alone is worth)                               (+ gate variant)
  P4  JRM, trained old       history-consistent training with the frozen minutes, served with JRM minutes (the 'trained on the old minutes distribution' hypothesis)
Dispersions of the negative-binomial yardstick are fitted on the VALIDATION seasons per configuration and used for the holdout (CRPS, intervals, betting-rung probabilities).
python evaluate_downstream_diagnosis.py OUT.md
"""
import sys
sys.path.insert(0, ".."); sys.path.insert(0, ".")
import json
import numpy as np, pandas as pd
from pf_core import models
from nba.common import FAMILIES, SUPPORT_K, VAL, HOLDOUT
from nba.evaluate import diff_ci
from nba import minutes_jrm as jrm

out_path = sys.argv[1]
frozen = json.load(open("../results/frozen_params.json"))
f = pd.read_parquet("../.cache/features.parquet", columns=["game_id", "team", "season", "pid", "played", "minutes", "in_box", "dnp", "dnp_reason", "pts", "reb", "ast", "fg3m", "fga", "pra",
                    "start_p_ewm8", "games_in_season", "team_changed", "games_with_team", "minutes_p_n", "missed_streak", "minutes_p_ewm8"])
mp = pd.read_parquet("../.cache/minutes_preds.parquet")
f = f.join(mp[["E", "p_play"]])
f["elig"] = jrm.eligible_flag(f)
g = f.groupby(["game_id", "team"])
f["n_elig"] = g.elig.transform("sum")
f["lvl"] = f.minutes_p_ewm8.fillna(0)
f["rank"] = f.groupby(["game_id", "team"])["lvl"].rank(ascending=False, method="first")
Ms = (f.p_play * f.E).groupby([f.game_id, f.team]).transform("sum")
f["gate"] = np.where((Ms / 241.5 - 1).abs() > 0.12, (241.5 / Ms).clip(0.55, 1.45), 1.0)       # nba/live/reconcile.py minutes scale (cfg defaults)
f["bigM"] = (Ms / 241.5 - 1).abs() > 0.12
f["split"] = np.where(f.season.isin(VAL), "val", np.where(f.season.isin(HOLDOUT), "holdout", "other"))
f = f[f.split != "other"]

lines = []
def out(s=""):
    print(s); lines.append(s)
def fmt(r):
    return "—" if r is None else f"{r['mean_diff']:+.3f} [{r['ci95'][0]:+.3f}, {r['ci95'][1]:+.3f}]"
def fmt4(r):
    return "—" if r is None else f"{r['mean_diff']:+.4f} [{r['ci95'][0]:+.4f}, {r['ci95'][1]:+.4f}]"

CFG = {"P0": "P0 production frozen (live recipe + gate)", "P1": "P1 JRM + existing models (live recipe)", "P2": "P2 JRM + refitted models (challenger)",
       "P3": "P3 frozen + refitted models (no gate)", "P3g": "P3g frozen + refitted models + gate", "P4": "P4 JRM, models trained on old minutes"}
COH = [("all players", lambda P: P.played),
       ("established starters", lambda P: P.start_p_ewm8.fillna(0) >= .5),
       ("bench-role", lambda P: P.start_p_ewm8.fillna(0) < .5),
       ("fringe rotation (team level rank 9-12)", lambda P: (P["rank"] >= 9) & (P["rank"] <= 12)),
       ("uncertain: new-to-team or < 5 games with team", lambda P: (P.team_changed == 1) | (P.games_with_team < 5)),
       ("deep rosters (15+ eligible)", lambda P: P.n_elig >= 15),
       ("first five games of the season", lambda P: P.games_in_season <= 4),
       ("teams the live gate must normalise (>12%)", lambda P: P.bigM)]

summary = []
out("# Downstream stat models and the minutes engine: root-cause comparison (generated by evaluate_downstream_diagnosis.py)\n")
for fam, (col, gkey, rungs) in FAMILIES.items():
    best = frozen["families"][fam]["best"]; K = SUPPORT_K[col]
    L0 = pd.read_parquet(f"../.cache/dl_L_frozen_{col}.parquet")[best]
    L1 = pd.read_parquet(f"../.cache/dl_L_jrm_{col}.parquet")[best]
    L4 = pd.read_parquet(f"../.cache/dl_H_mismatch_{col}.parquet")[best]
    H0 = pd.read_parquet(f"../.cache/stats_{col}.parquet")[best]
    H1 = pd.read_parquet(f"../.cache/ds_jrm_{col}_v2.parquet")[best]
    P = f.join(pd.DataFrame({"L0": L0, "L1": L1, "L4": L4, "H0": H0, "H1": H1}), how="inner")
    P = P[P.played & P[col].notna() & P[["L0", "L1", "L4", "H0", "H1"]].notna().all(axis=1)].copy()
    P["P0"] = P.L0 * P.gate; P["P0u"] = P.L0; P["P1"] = P.L1; P["P2"] = P.H1; P["P3"] = P.H0; P["P3g"] = P.H0 * P.gate; P["P4"] = P.L4
    y = P[col].to_numpy(float); val = (P.split == "val").to_numpy(); hold = (P.split == "holdout").to_numpy()
    gid = P.game_id.to_numpy()
    prm, dist = {}, {}
    for k in CFG:
        mu = np.maximum(P[k].to_numpy(float), 0.05)
        prm[k] = models.fit_dist_params("nb_binned", y[val], mu[val], K=K, n_bins=6)
        dist[k] = models.make_dist(prm[k], mu)
    crps = {k: dist[k].crps(y) for k in CFG}
    iv = {k: dist[k].interval(0.8) for k in CFG}
    lo80 = {k: iv[k][0] for k in CFG}; hi80 = {k: iv[k][1] for k in CFG}
    out(f"\n## {fam} (published model: {best}; n holdout = {int(hold.sum()):,}, validation = {int(val.sum()):,})\n")
    out("| configuration | split | MAE | bias | bias % of mean | CRPS | 80% coverage | ΔMAE vs P0 [95% CI] | ΔCRPS vs P0 [95% CI] |\n|---|---|---:|---:|---:|---:|---:|---|---|")
    for sp, m in (("val", val), ("holdout", hold)):
        for k in CFG:
            mu = P[k].to_numpy(float)[m]
            ae = np.abs(mu - y[m])
            dm = diff_ci(ae, np.abs(P["P0"].to_numpy(float)[m] - y[m]), gid[m]) if k != "P0" else None
            dc = diff_ci(crps[k][m], crps["P0"][m], gid[m]) if k != "P0" else None
            cov = float(np.mean((y[m] >= lo80[k][m]) & (y[m] <= hi80[k][m])))
            out(f"| {CFG[k]} | {sp} | {ae.mean():.3f} | {np.mean(mu - y[m]):+.3f} | {100 * np.mean(mu - y[m]) / y[m].mean():+.1f}% | {crps[k][m].mean():.4f} | {cov:.3f} | {fmt(dm)} | {fmt4(dc)} |")
        if sp == "val":
            continue
        mu = P["P0u"].to_numpy(float)[m]
        out(f"| (P0 without the gate: frozen live recipe) | {sp} | {np.abs(mu - y[m]).mean():.3f} | {np.mean(mu - y[m]):+.3f} | {100 * np.mean(mu - y[m]) / y[m].mean():+.1f}% | | | | |")
    # cohorts (holdout)
    out(f"\n**{fam}: cohorts, holdout (MAE / bias; paired ΔMAE vs P0)**\n")
    out("| cohort | n | P0 MAE / bias | P1 MAE / bias | P2 MAE / bias | P2 − P0 ΔMAE [95% CI] | P2 − P1 ΔMAE [95% CI] |\n|---|---:|---|---|---|---|---|")
    for cname, fn in COH:
        m = (fn(P) & (P.split == "holdout")).to_numpy()
        if m.sum() < 300:
            out(f"| {cname} | {int(m.sum())} | (< 300) | | | | |"); continue
        cell = lambda k: f"{np.abs(P[k].to_numpy(float)[m] - y[m]).mean():.3f} / {np.mean(P[k].to_numpy(float)[m] - y[m]):+.3f}"
        a0, a1, a2 = (np.abs(P[k].to_numpy(float)[m] - y[m]) for k in ("P0", "P1", "P2"))
        out(f"| {cname} | {int(m.sum()):,} | {cell('P0')} | {cell('P1')} | {cell('P2')} | {fmt(diff_ci(a2, a0, gid[m]))} | {fmt(diff_ci(a2, a1, gid[m]))} |")
    # betting-rung probabilities: P(X >= k) at the rungs the props use
    out(f"\n**{fam}: probabilities at the betting rungs {rungs}, holdout (mean Brier over rungs; lower is better) and tail reliability**\n")
    out("| configuration | rung Brier | P(X≥k) mean predicted | observed | top-tail: pred / obs where P(X≥k) ≥ 0.8 (n) | bottom-tail: pred / obs where P(X≥k) ≤ 0.1 (n) |\n|---|---:|---:|---:|---|---|")
    base_b = {}
    for k in CFG:
        pr = np.column_stack([dist[k].prob_ge(r)[hold] for r in rungs]); ob = np.column_stack([(y[hold] >= r).astype(float) for r in rungs])
        br = ((pr - ob) ** 2).mean(axis=0)
        hi = pr >= 0.8; lo = pr <= 0.1
        out(f"| {CFG[k]} | {br.mean():.4f} | {pr.mean():.3f} | {ob.mean():.3f} | {pr[hi].mean():.3f} / {ob[hi].mean():.3f} ({int(hi.sum())}) | {pr[lo].mean():.3f} / {ob[lo].mean():.3f} ({int(lo.sum())}) |")
        base_b[k] = (((pr - ob) ** 2).mean(axis=1))
    d = diff_ci(base_b["P2"], base_b["P0"], gid[hold]); d1 = diff_ci(base_b["P1"], base_b["P0"], gid[hold])
    out(f"\nPaired rung-Brier difference vs P0 (holdout): P2 {fmt4(d)}; P1 {fmt4(d1)}.")
    for k in ("P1", "P2"):
        mh = hold
        summary.append((fam, k, diff_ci(np.abs(P[k].to_numpy(float)[mh] - y[mh]), np.abs(P["P0"].to_numpy(float)[mh] - y[mh]), gid[mh]), diff_ci(crps[k][mh], crps["P0"][mh], gid[mh]),
                        float(np.mean(P[k].to_numpy(float)[mh] - y[mh])), float(np.mean(P["P0"].to_numpy(float)[mh] - y[mh])), int(mh.sum())))
out("\n## Roll-up, holdout, against P0 (negative Δ = better than production frozen)\n")
out("| family | n | P1 ΔMAE | P1 ΔCRPS | P1 bias (P0 bias) | P2 ΔMAE | P2 ΔCRPS | P2 bias |\n|---|---:|---|---|---|---|---|---|")
for fam in FAMILIES:
    a = [s for s in summary if s[0] == fam and s[1] == "P1"][0]; b = [s for s in summary if s[0] == fam and s[1] == "P2"][0]
    out(f"| {fam} | {a[6]:,} | {fmt(a[2])} | {fmt4(a[3])} | {a[4]:+.3f} ({a[5]:+.3f}) | {fmt(b[2])} | {fmt4(b[3])} | {b[4]:+.3f} |")
open(out_path, "w").write("\n".join(lines))
